const {
  DeleteObjectCommand,
  GetObjectCommand,
  PutObjectCommand
} = require(
  '@aws-sdk/client-s3'
);

const env =
  require('../config/env');

const {
  r2Client,
  isR2Enabled
} = require(
  '../config/r2'
);


/*
 * ============================================================
 * R2 OBJECT STORAGE SERVICE
 * ============================================================
 *
 * This file contains only low-level R2 operations.
 *
 * Application routes should eventually use a higher-level
 * storage abstraction rather than constructing S3 commands
 * themselves.
 */


/**
 * Ensure the application is actually running with R2 enabled
 * before any Cloudflare operation is attempted.
 */
function requireR2Client() {
  if (
    !isR2Enabled() ||
    !r2Client
  ) {
    throw new Error(
      'Cloudflare R2 storage is not enabled.'
    );
  }

  return r2Client;
}


/**
 * Restrict bucket selection to the two buckets explicitly
 * configured by the application.
 */
function resolveBucket(
  visibility
) {
  if (
    visibility ===
    'public'
  ) {
    return env.r2PublicBucket;
  }


  if (
    visibility ===
    'private'
  ) {
    return env.r2PrivateBucket;
  }


  throw new Error(
    'Storage visibility must be either public or private.'
  );
}


/**
 * Validate object keys before sending them to object storage.
 *
 * Object keys are generated by our application and must never
 * begin with a slash.
 */
function validateObjectKey(
  objectKey
) {
  if (
    typeof objectKey !==
      'string' ||
    !objectKey.trim()
  ) {
    throw new Error(
      'A storage object key is required.'
    );
  }


  if (
    objectKey.startsWith('/')
  ) {
    throw new Error(
      'Storage object keys must not begin with a slash.'
    );
  }


  return objectKey;
}


/**
 * Upload one object to either the public or private R2 bucket.
 */
async function putR2Object({
  visibility,
  objectKey,
  body,
  contentType,
  cacheControl
}) {
  const client =
    requireR2Client();

  const bucket =
    resolveBucket(
      visibility
    );

  const key =
    validateObjectKey(
      objectKey
    );


  if (
    body === undefined ||
    body === null
  ) {
    throw new Error(
      'An object body is required.'
    );
  }


  const commandInput = {
    Bucket:
      bucket,

    Key:
      key,

    Body:
      body
  };


  if (contentType) {
    commandInput.ContentType =
      contentType;
  }


  if (cacheControl) {
    commandInput.CacheControl =
      cacheControl;
  }


  const result =
    await client.send(
      new PutObjectCommand(
        commandInput
      )
    );


  return {
    bucket,
    objectKey:
      key,

    etag:
      result.ETag || null
  };
}


/**
 * Retrieve one object.
 *
 * This will mainly be used for protected résumé downloads.
 */
async function getR2Object({
  visibility,
  objectKey
}) {
  const client =
    requireR2Client();

  const bucket =
    resolveBucket(
      visibility
    );

  const key =
    validateObjectKey(
      objectKey
    );


  return client.send(
    new GetObjectCommand({
      Bucket:
        bucket,

      Key:
        key
    })
  );
}


/**
 * Delete one object.
 */
async function deleteR2Object({
  visibility,
  objectKey
}) {
  const client =
    requireR2Client();

  const bucket =
    resolveBucket(
      visibility
    );

  const key =
    validateObjectKey(
      objectKey
    );


  await client.send(
    new DeleteObjectCommand({
      Bucket:
        bucket,

      Key:
        key
    })
  );


  return {
    deleted:
      true,

    bucket,

    objectKey:
      key
  };
}


/**
 * Build the browser-facing URL for a PUBLIC object.
 *
 * Private résumé files must never use this function.
 */
function buildPublicR2Url(
  objectKey
) {
  const key =
    validateObjectKey(
      objectKey
    );


  if (
    !env.r2PublicBaseUrl
  ) {
    throw new Error(
      'R2 public base URL is not configured.'
    );
  }


  const encodedKey =
    key
      .split('/')
      .map(
        (segment) =>
          encodeURIComponent(
            segment
          )
      )
      .join('/');


  return (
    `${env.r2PublicBaseUrl}/${encodedKey}`
  );
}


module.exports = {
  putR2Object,
  getR2Object,
  deleteR2Object,
  buildPublicR2Url
};