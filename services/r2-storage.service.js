const {
  DeleteObjectCommand,
  GetObjectCommand,
  PutObjectCommand
} = require(
  '@aws-sdk/client-s3'
);

const env =
  require('../config/env');

const {
  r2Client,
  isR2Enabled
} = require(
  '../config/r2'
);

const logger =
require('../config/logger');

/**
 * Return the HTTP status code supplied by the S3-compatible
 * R2 API when one is available.
 */
function getR2ErrorStatusCode(
  error
) {
  const statusCode =
    Number(
      error?.$metadata
        ?.httpStatusCode
    );

  return Number.isFinite(
    statusCode
  )
    ? statusCode
    : null;
}


/**
 * Detect the normal S3/R2 representation of a missing object.
 */
function isR2MissingObjectError(
  error
) {
  return Boolean(
    error &&
    (
      error.name ===
        'NoSuchKey' ||

      error.Code ===
        'NoSuchKey' ||

      getR2ErrorStatusCode(
        error
      ) === 404
    )
  );
}


/**
 * Return only the controlled storage category from an object
 * key.
 *
 * We deliberately do not log the complete object key because
 * private object names should not become operational log data.
 *
 * Examples:
 *
 * news/example.jpg       -> news
 * digests/file.pdf       -> digests
 * rate-guide/file.webp   -> rate-guide
 * resumes/random.pdf     -> resumes
 */
function getR2ObjectCategory(
  objectKey
) {
  if (
    typeof objectKey !==
      'string'
  ) {
    return null;
  }

  const [
    category
  ] =
    objectKey.split('/');

  return category || null;
}

/*
 * ============================================================
 * R2 OBJECT STORAGE SERVICE
 * ============================================================
 *
 * This file contains only low-level R2 operations.
 *
 * Application routes should eventually use a higher-level
 * storage abstraction rather than constructing S3 commands
 * themselves.
 */


/**
 * Ensure the application is actually running with R2 enabled
 * before any Cloudflare operation is attempted.
 */
function requireR2Client() {
  if (
    !isR2Enabled() ||
    !r2Client
  ) {
    throw new Error(
      'Cloudflare R2 storage is not enabled.'
    );
  }

  return r2Client;
}


/**
 * Restrict bucket selection to the two buckets explicitly
 * configured by the application.
 */
function resolveBucket(
  visibility
) {
  if (
    visibility ===
    'public'
  ) {
    return env.r2PublicBucket;
  }


  if (
    visibility ===
    'private'
  ) {
    return env.r2PrivateBucket;
  }


  throw new Error(
    'Storage visibility must be either public or private.'
  );
}


/**
 * Validate object keys before sending them to object storage.
 *
 * Object keys are generated by our application and must never
 * begin with a slash.
 */
function validateObjectKey(
  objectKey
) {
  if (
    typeof objectKey !==
      'string' ||
    !objectKey.trim()
  ) {
    throw new Error(
      'A storage object key is required.'
    );
  }


  if (
    objectKey.startsWith('/')
  ) {
    throw new Error(
      'Storage object keys must not begin with a slash.'
    );
  }


  return objectKey;
}


/**
 * Upload one object to either the public or private R2 bucket.
 */
/**
 * Upload one object to either the public or private R2 bucket.
 */
async function putR2Object({
  visibility,
  objectKey,
  body,
  contentType,
  cacheControl
}) {
  try {
    const client =
      requireR2Client();

    const bucket =
      resolveBucket(
        visibility
      );

    const key =
      validateObjectKey(
        objectKey
      );

    if (
      body === undefined ||
      body === null
    ) {
      throw new Error(
        'An object body is required.'
      );
    }

    const commandInput = {
      Bucket:
        bucket,

      Key:
        key,

      Body:
        body
    };

    if (contentType) {
      commandInput.ContentType =
        contentType;
    }

    if (cacheControl) {
      commandInput.CacheControl =
        cacheControl;
    }

    const result =
      await client.send(
        new PutObjectCommand(
          commandInput
        )
      );

    return {
      bucket,

      objectKey:
        key,

      etag:
        result.ETag || null
    };
  } catch (error) {
    logger.error(
      {
        err:
          error,

        event:
          'STORAGE_UPLOAD_FAILED',

        component:
          'storage',

        dependency:
          'cloudflare-r2',

        driver:
          'r2',

        operation:
          'upload',

        visibility,

        category:
          getR2ObjectCategory(
            objectKey
          ),

        httpStatusCode:
          getR2ErrorStatusCode(
            error
          )
      },

      'Cloudflare R2 upload failed'
    );

    throw error;
  }
}



/**
 * Retrieve one object.
 *
 * This will mainly be used for protected résumé downloads.
 */
async function getR2Object({
  visibility,
  objectKey
}) {
  try {
    const client =
      requireR2Client();

    const bucket =
      resolveBucket(
        visibility
      );

    const key =
      validateObjectKey(
        objectKey
      );

    return await client.send(
      new GetObjectCommand({
        Bucket:
          bucket,

        Key:
          key
      })
    );
  } catch (error) {
    const logContext = {
      err:
        error,

      component:
        'storage',

      dependency:
        'cloudflare-r2',

      driver:
        'r2',

      operation:
        'read',

      visibility,

      category:
        getR2ObjectCategory(
          objectKey
        ),

      httpStatusCode:
        getR2ErrorStatusCode(
          error
        )
    };

    if (
      isR2MissingObjectError(
        error
      )
    ) {
      logger.warn(
        {
          ...logContext,

          event:
            'STORAGE_OBJECT_NOT_FOUND'
        },

        'Cloudflare R2 object was not found'
      );
    } else {
      logger.error(
        {
          ...logContext,

          event:
            'STORAGE_READ_FAILED'
        },

        'Cloudflare R2 read failed'
      );
    }

    throw error;
  }
}


/**
 * Delete one object.
 */
async function deleteR2Object({
  visibility,
  objectKey
}) {
  try {
    const client =
      requireR2Client();

    const bucket =
      resolveBucket(
        visibility
      );

    const key =
      validateObjectKey(
        objectKey
      );

    await client.send(
      new DeleteObjectCommand({
        Bucket:
          bucket,

        Key:
          key
      })
    );

    return {
      deleted:
        true,

      bucket,

      objectKey:
        key
    };
  } catch (error) {
    logger.error(
      {
        err:
          error,

        event:
          'STORAGE_DELETE_FAILED',

        component:
          'storage',

        dependency:
          'cloudflare-r2',

        driver:
          'r2',

        operation:
          'delete',

        visibility,

        category:
          getR2ObjectCategory(
            objectKey
          ),

        httpStatusCode:
          getR2ErrorStatusCode(
            error
          )
      },

      'Cloudflare R2 delete failed'
    );

    throw error;
  }
}


/**
 * Build the browser-facing URL for a PUBLIC object.
 *
 * Private résumé files must never use this function.
 */
function buildPublicR2Url(
  objectKey
) {
  const key =
    validateObjectKey(
      objectKey
    );


  if (
    !env.r2PublicBaseUrl
  ) {
    throw new Error(
      'R2 public base URL is not configured.'
    );
  }


  const encodedKey =
    key
      .split('/')
      .map(
        (segment) =>
          encodeURIComponent(
            segment
          )
      )
      .join('/');


  return (
    `${env.r2PublicBaseUrl}/${encodedKey}`
  );
}


