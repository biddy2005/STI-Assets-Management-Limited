const fs =
  require('fs/promises');

const path =
  require('path');

const env =
  require('../config/env');

const {
  resumeDirectory,
  digestUploadDirectory,
  newsUploadDirectory,
  rateGuideUploadDirectory
} = require(
  '../config/storage'
);

const {
  putR2Object,
  getR2Object,
  deleteR2Object,
  buildPublicR2Url
} = require(
  './r2-storage.service'
);


/*
 * ============================================================
 * STORAGE ABSTRACTION
 * ============================================================
 *
 * Routes should eventually interact with this service rather
 * than knowing whether files are stored on the local
 * filesystem or Cloudflare R2.
 *
 * Supported drivers:
 *
 * local
 * r2
 */


/*
 * Public storage categories.
 *
 * Each category maps to:
 *
 * - its current local filesystem folder;
 * - its R2 object-key prefix;
 * - its current browser-facing local URL prefix.
 */
const publicStorageCategories = {
  news: {
    localDirectory:
      newsUploadDirectory,

    objectPrefix:
      'news',

    localUrlPrefix:
      '/uploads/news'
  },

  digests: {
    localDirectory:
      digestUploadDirectory,

    objectPrefix:
      'digests',

    localUrlPrefix:
      '/uploads/digests'
  },

  rateGuide: {
    localDirectory:
      rateGuideUploadDirectory,

    objectPrefix:
      'rate-guide',

    localUrlPrefix:
      '/uploads/rate-guide'
  }
};


/*
 * Private files currently consist only of applicant résumés.
 */
const privateResumeObjectPrefix =
  'resumes';


/**
 * Returns the configured storage backend.
 */
function getStorageDriver() {
  return env.storageDriver;
}


/**
 * Storage filenames are generated by the application rather
 * than supplied directly by users.
 *
 * Keep storage keys to a single safe filename. Directory
 * prefixes such as "resumes/" and "news/" are controlled by
 * this service instead.
 */
function validateStorageKey(
  storageKey
) {
  if (
    typeof storageKey !==
      'string'
  ) {
    throw new Error(
      'A valid storage key is required.'
    );
  }


  const cleanedKey =
    storageKey.trim();


  if (
    !cleanedKey ||
    cleanedKey.length > 255
  ) {
    throw new Error(
      'A valid storage key is required.'
    );
  }


  /*
   * Only generated filenames are accepted.
   *
   * This deliberately rejects:
   *
   * ../file.pdf
   * folder/file.pdf
   * folder\file.pdf
   * hidden path tricks
   */
  const safeStorageKeyPattern =
    /^[A-Za-z0-9][A-Za-z0-9._-]{0,254}$/;


  if (
    !safeStorageKeyPattern.test(
      cleanedKey
    )
  ) {
    throw new Error(
      'Storage key contains unsupported characters.'
    );
  }


  return cleanedKey;
}


/**
 * Return configuration for one public storage category.
 */
function resolvePublicCategory(
  category
) {
  const configuration =
    publicStorageCategories[
      category
    ];


  if (!configuration) {
    throw new Error(
      'Unsupported public storage category.'
    );
  }


  return configuration;
}


/**
 * Convert an R2 GetObject body into a Buffer.
 *
 * Résumés are currently limited to 5 MB, so buffering one
 * authenticated résumé download is acceptable for this
 * application.
 */
async function r2BodyToBuffer(
  body
) {
  if (!body) {
    return Buffer.alloc(0);
  }


  /*
   * AWS SDK v3 adds convenience transformation methods to
   * GetObject streams in Node.js.
   */
  if (
    typeof body.transformToByteArray ===
      'function'
  ) {
    const bytes =
      await body
        .transformToByteArray();

    return Buffer.from(
      bytes
    );
  }


  /*
   * Defensive fallback for stream implementations that do not
   * expose transformToByteArray().
   */
  const chunks =
    [];


  for await (
    const chunk of body
  ) {
    chunks.push(
      Buffer.isBuffer(chunk)
        ? chunk
        : Buffer.from(chunk)
    );
  }


  return Buffer.concat(
    chunks
  );
}

/**
 * Create one provider-independent not-found error.
 *
 * Routes should not need to know whether the missing file came
 * from the local filesystem or Cloudflare R2.
 */
function createStorageFileNotFoundError() {
  const error =
    new Error(
      'The stored file could not be found.'
    );

  error.code =
    'STORAGE_FILE_NOT_FOUND';

  return error;
}


/**
 * Detect the normal R2/S3 not-found response.
 */
function isR2MissingObjectError(
  error
) {
  return Boolean(
    error &&
    (
      error.name ===
        'NoSuchKey' ||

      error.Code ===
        'NoSuchKey' ||

      Number(
        error.$metadata
          ?.httpStatusCode
      ) === 404
    )
  );
}


/**
 * Write one local file.
 */
async function writeLocalFile({
  directory,
  storageKey,
  body
}) {
  if (
    body === undefined ||
    body === null
  ) {
    throw new Error(
      'A file body is required.'
    );
  }


  await fs.mkdir(
    directory,
    {
      recursive:
        true
    }
  );


  const destinationPath =
    path.join(
      directory,
      storageKey
    );


  await fs.writeFile(
    destinationPath,
    body
  );


  return destinationPath;
}


/**
 * Delete one local file.
 *
 * Missing files are treated as already deleted.
 */
async function deleteLocalFile(
  filePath
) {
  try {
    await fs.unlink(
      filePath
    );

    return true;
  } catch (error) {
    if (
      error.code ===
        'ENOENT'
    ) {
      return false;
    }


    throw error;
  }
}


/**
 * Save a PUBLIC website file.
 *
 * Supported categories:
 *
 * news
 * digests
 * rateGuide
 */
async function savePublicFile({
  category,
  storageKey,
  body,
  contentType,
  cacheControl
}) {
  const key =
    validateStorageKey(
      storageKey
    );


  const configuration =
    resolvePublicCategory(
      category
    );


  if (
    env.storageDriver ===
      'local'
  ) {
    const localPath =
      await writeLocalFile({
        directory:
          configuration
            .localDirectory,

        storageKey:
          key,

        body
      });


    return {
      driver:
        'local',

      storageKey:
        key,

      localPath,

      publicUrl:
        `${configuration.localUrlPrefix}/${encodeURIComponent(key)}`
    };
  }


  const objectKey =
    `${configuration.objectPrefix}/${key}`;


  await putR2Object({
    visibility:
      'public',

    objectKey,

    body,

    contentType,

    cacheControl
  });


  return {
    driver:
      'r2',

    storageKey:
      key,

    objectKey,

    publicUrl:
      buildPublicR2Url(
        objectKey
      )
  };
}


/**
 * Return the browser-facing URL for an existing public file.
 */
function getPublicFileUrl({
  category,
  storageKey
}) {
  const key =
    validateStorageKey(
      storageKey
    );


  const configuration =
    resolvePublicCategory(
      category
    );


  if (
    env.storageDriver ===
      'local'
  ) {
    return (
      `${configuration.localUrlPrefix}/${encodeURIComponent(key)}`
    );
  }


  return buildPublicR2Url(
    `${configuration.objectPrefix}/${key}`
  );
}


/**
 * Delete one PUBLIC website file.
 */
async function deletePublicFile({
  category,
  storageKey
}) {
  const key =
    validateStorageKey(
      storageKey
    );


  const configuration =
    resolvePublicCategory(
      category
    );


  if (
    env.storageDriver ===
      'local'
  ) {
    const localPath =
      path.join(
        configuration
          .localDirectory,

        key
      );


    const deleted =
      await deleteLocalFile(
        localPath
      );


    return {
      driver:
        'local',

      storageKey:
        key,

      deleted
    };
  }


  const objectKey =
    `${configuration.objectPrefix}/${key}`;


  await deleteR2Object({
    visibility:
      'public',

    objectKey
  });


  return {
    driver:
      'r2',

    storageKey:
      key,

    objectKey,

    deleted:
      true
  };
}


/**
 * Save one PRIVATE applicant résumé.
 */
async function savePrivateFile({
  storageKey,
  body,
  contentType
}) {
  const key =
    validateStorageKey(
      storageKey
    );


  if (
    env.storageDriver ===
      'local'
  ) {
    const localPath =
      await writeLocalFile({
        directory:
          resumeDirectory,

        storageKey:
          key,

        body
      });


    return {
      driver:
        'local',

      storageKey:
        key,

      localPath
    };
  }


  const objectKey =
    `${privateResumeObjectPrefix}/${key}`;


  await putR2Object({
    visibility:
      'private',

    objectKey,

    body,

    contentType,

    /*
     * Private résumés must not be cached as public assets.
     */
    cacheControl:
      'private, no-store'
  });


  return {
    driver:
      'r2',

    storageKey:
      key,

    objectKey
  };
}


/**
 * Retrieve one PRIVATE applicant résumé.
 */
async function getPrivateFile({
  storageKey
}) {
  const key =
    validateStorageKey(
      storageKey
    );


  if (
    env.storageDriver ===
      'local'
  ) {
    const localPath =
      path.join(
        resumeDirectory,
        key
      );


 let body;


    try {
      body =
        await fs.readFile(
          localPath
        );
    } catch (error) {
      if (
        error.code ===
          'ENOENT'
      ) {
        throw createStorageFileNotFoundError();
      }


      throw error;
    }


    return {
      driver:
        'local',

      storageKey:
        key,

      body,

      contentType:
        key
          .toLowerCase()
          .endsWith('.pdf')
          ? 'application/pdf'
          : 'application/octet-stream',

      contentLength:
        body.length
    };
  }


  const objectKey =
    `${privateResumeObjectPrefix}/${key}`;


    let object;


  try {
    object =
      await getR2Object({
        visibility:
          'private',

        objectKey
      });
  } catch (error) {
    if (
      isR2MissingObjectError(
        error
      )
    ) {
      throw createStorageFileNotFoundError();
    }


    throw error;
  }


  const body =
    await r2BodyToBuffer(
      object.Body
    );


  return {
    driver:
      'r2',

    storageKey:
      key,

    objectKey,

    body,

    contentType:
      object.ContentType ||
      'application/octet-stream',

    contentLength:
      Number(
        object.ContentLength
      ) ||
      body.length
  };
}


